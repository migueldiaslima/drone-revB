# Figures for the v04-B section 9 checks (ASCII only)
import numpy as np, matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Rectangle, Circle, Polygon
R3=47.45; RB=44.45; M=49.5
def style(ax,t):
    ax.set_aspect("equal"); ax.grid(alpha=.3); ax.set_title(t,fontsize=10)
# 1 plan view top band
f,ax=plt.subplots(figsize=(7,7))
octo=[(20,11.8),(11.8,20),(-11.8,20),(-20,11.8),(-20,-11.8),(-11.8,-20),(11.8,-20),(20,-11.8)]
ax.add_patch(Polygon(octo,fc="#cfe2f3",ec="b",label="upper body outline z 10 to 21.5 (|x|+|y| <= 31.8)"))
ax.add_patch(Rectangle((-16.5,-16.5),33,33,fc="none",ec="r",lw=2,label="FC board 33 x 33"))
ax.add_patch(Rectangle((-17,-17),34,34,fc="none",ec="r",ls="--",label="insertion prism K2, 34 x 34"))
for sx in (1,-1):
    for sy in (1,-1):
        ax.add_patch(Circle((sx*M,sy*M),R3,fc="#f4cccc",ec="m",alpha=.5))
        ax.add_patch(Circle((sx*12.75,sy*12.75),4,fc="none",ec="g",ls=":"))
        ax.add_patch(Circle((sx*20.25,sy*7),3,fc="orange",ec="k"))
ax.add_patch(Circle((-26,0),3,fc="orange",ec="k",label="lid bosses dia 6"))
ax.plot([],[],color="m",lw=6,alpha=.5,label="prop sweep + 3 mm (z 10 to 21.5)")
ax.plot([],[],color="g",ls=":",label="nut access columns dia 8")
ax.plot([16.5],[16.5],"ro"); ax.annotate("board corner 23.3 mm out\nchamfer at 22.5 mm",(16.5,16.5),(22,24),arrowprops=dict(arrowstyle="->"))
ax.set_xlim(-32,32); ax.set_ylim(-32,32); style(ax,"Check 1: plan view of the top band (z 10 to 21.5)")
ax.legend(loc="lower left",fontsize=7); ax.set_xlabel("x (mm), forward"); ax.set_ylabel("y (mm), left")
f.savefig("check1_plan.png",dpi=150,bbox_inches="tight")
# 3 keel corridor plan
f,ax=plt.subplots(figsize=(8,5))
xs=np.linspace(-52,-18,200)
def yl(x,R): return M-np.sqrt(R*R-(np.abs(x)-M)**2)
ax.fill_between(xs,yl(xs,R3),20,color="#f4cccc",label="prop sweep + 3 mm")
ax.fill_between(xs,-20,-yl(xs,R3),color="#f4cccc")
ax.plot(xs,yl(xs,RB),"m--",label="blade tip path"); ax.plot(xs,-yl(xs,RB),"m--")
kx=np.linspace(-50,-19,100); kh=np.minimum(9,yl(kx,R3))
ax.fill_between(kx,-kh,kh,color="#cfe2f3",label="keel above z = 10 (fills the corridor)")
ax.add_patch(Circle((-36,5.5),1.5,fc="k")); ax.annotate("dia 3 cable beside the keel at x = -36:\nouter edge 0.15 mm from the blade tips",(-36,5.5),(-34,14),arrowprops=dict(arrowstyle="->"))
ax.add_patch(Circle((-33,0),2,fc="w",ec="k")); ax.annotate("default: dia 4 channel inside keel",(-33,0),(-31,-6),arrowprops=dict(arrowstyle="->"))
ax.add_patch(Rectangle((-20,-20),2,40,fc="grey",alpha=.4)); ax.text(-19.6,-18,"body\nrear\nface",fontsize=7)
ax.set_xlim(-52,-17); ax.set_ylim(-20,20); style(ax,"Check 3: plan view behind the body at blade height (z 10 to 21.5)")
ax.legend(loc="lower left",fontsize=7); ax.set_xlabel("x (mm)"); ax.set_ylabel("y (mm)")
f.savefig("check3_keel.png",dpi=150,bbox_inches="tight")
